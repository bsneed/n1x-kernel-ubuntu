# Tests of lib-i2c-hid.sh (the ProArt P16's i2c-hid: install.sh deleting the old early-load
# drop-in, check.sh finding patches/ubuntu/0002 in the module), with fake files.
# Sourced by tests/run.sh, which defines eq, fails, skip and $T.
# shellcheck shell=bash
. scripts/lib-i2c-hid.sh
DMI_PRODUCT=$T/ih-product EARLY_DRACUT=$T/ih-etc/dracut.conf.d/50-i2c-hid-early.conf
P16='ProArt P16 H7607BA'

# --- which machine ------------------------------------------------------------------------------
echo "$P16" >"$DMI_PRODUCT"
eq "P16: the H7607BA" 0 "$(is_proart_p16; echo $?)"
echo 'Zenbook A14 UX3407QA' >"$DMI_PRODUCT"
eq "P16: not another laptop" 1 "$(is_proart_p16; echo $?)"
eq "P16: not without DMI" 1 "$(DMI_PRODUCT=$T/none is_proart_p16; echo $?)"

# --- install.sh deletes the early-load drop-in that the n1x3/n1x4 install.sh wrote ----------------
mkdir -p "${EARLY_DRACUT%/*}"
# What that install.sh wrote (early_dracut_text on bsneed/i2c-hid-shutdown-quirk), as on rtx24.
ours() {
	cat <<-EOF
		# Generated by n1x-kernel-ubuntu (scripts/install.sh): load the ProArt P16's i2c-hid drivers early,
		# from the initramfs. With touchpad firmware V1.26.0918.1 the keyboard and touchpad die on
		# a warm reboot if they are probed late (docs/i2c-hid-warm-reboot.md).
		# scripts/install.sh --remove deletes this. Remove by hand: sudo rm $EARLY_DRACUT;
		# sudo update-initramfs -u -k all
		force_drivers+=" i2c_mt65xx i2c_hid i2c_hid_acpi "
	EOF
}
# The hand-written one rtx24 had before that install.sh took it over: the same setting.
hand() {
	printf '%s\n' '# rtx24: load the i2c-hid drivers early in the initramfs.' \
		'force_drivers+=" i2c_mt65xx i2c_hid i2c_hid_acpi "'
}
drop() { (early_load_drop) >"$T/ih-out" 2>"$T/ih-err"; echo "$?"; }
ours >"$EARLY_DRACUT"
eq "drop-in: ours is ours" 0 "$(early_dracut_is_ours "$EARLY_DRACUT"; echo $?)"
eq "drop-in: missing is not ours" 1 "$(early_dracut_is_ours "$T/none"; echo $?)"
hand >"$T/ih-hand"
eq "drop-in: hand-written is not ours" 1 "$(early_dracut_is_ours "$T/ih-hand"; echo $?)"
printf '# rtx24\n%s\n' "$(ours)" >"$T/ih-late"
eq "drop-in: our header on line 2 is not ours" 1 "$(early_dracut_is_ours "$T/ih-late"; echo $?)"
printf '# Generated by n1x-kernel-ubuntu: something else\n' >"$T/ih-other"
eq "drop-in: another header of ours is not this one" 1 "$(early_dracut_is_ours "$T/ih-other"; echo $?)"
mkdir -p "$T/ih-dir"
eq "drop-in: a directory is not ours" 1 "$(early_dracut_is_ours "$T/ih-dir"; echo $?)"

echo "$P16" >"$DMI_PRODUCT"
ours >"$EARLY_DRACUT"
eq "P16, ours: removed" "0|absent" "$(drop)|$([[ -e $EARLY_DRACUT ]] && echo present || echo absent)"
eq "P16, ours: says so" "==> Removed $EARLY_DRACUT: i2c-hid no longer needs to load early (patches/ubuntu/0002)" "$(cat "$T/ih-out")"
eq "P16, ours: no warning" "" "$(cat "$T/ih-err")"
eq "P16, ours: the directory stays" 1 "$([[ -d ${EARLY_DRACUT%/*} ]] && echo 1)"
# A drop-in of ours that someone edited below the header is still ours.
{ ours; echo 'add_drivers+=" hid_multitouch "'; } >"$EARLY_DRACUT"
eq "P16, ours edited below the header: removed" "0|absent" "$(drop)|$([[ -e $EARLY_DRACUT ]] && echo present || echo absent)"
hand >"$EARLY_DRACUT"
eq "P16, hand-written: left as it was" "0|$(hand)" "$(drop)|$(cat "$EARLY_DRACUT")"
eq "P16, hand-written: a warning" "WARNING: $EARLY_DRACUT was not written by install.sh, so it stays as it is. The keyboard and touchpad don't need i2c-hid loaded early any more (docs/i2c-hid-probe-retry.md); delete it if you don't need it for anything else." \
	"$(cat "$T/ih-err")"
eq "P16, hand-written: nothing on stdout" "" "$(cat "$T/ih-out")"
cp "$T/ih-late" "$EARLY_DRACUT"
eq "P16, our text under another first line: left" "0|1" "$(drop)|$(cmp -s "$T/ih-late" "$EARLY_DRACUT" && echo 1)"
eq "P16, our text under another first line: a warning" 1 "$(grep -c '^WARNING: .* was not written by install.sh' "$T/ih-err")"
: >"$EARLY_DRACUT"
eq "P16, empty file: left, with a warning" "0|present|1" "$(drop)|$([[ -e $EARLY_DRACUT ]] && echo present)|$(grep -c '^WARNING: ' "$T/ih-err")"
rm -f "$EARLY_DRACUT"
ln -s "$T/none" "$EARLY_DRACUT"
eq "P16, dangling symlink: left, with a warning" "0|link|1" "$(drop)|$([[ -L $EARLY_DRACUT ]] && echo link)|$(grep -c '^WARNING: ' "$T/ih-err")"
rm -f "$EARLY_DRACUT"
eq "P16, absent: nothing to do" "0||" "$(drop)|$(cat "$T/ih-out")|$(cat "$T/ih-err")"
rm -rf "${EARLY_DRACUT%/*}"
eq "P16, no dracut.conf.d: nothing to do" "0||" "$(drop)|$(cat "$T/ih-out")|$(cat "$T/ih-err")"
mkdir -p "${EARLY_DRACUT%/*}"
for m in 'Zenbook A14 UX3407QA' ''; do
	printf '%s\n' "$m" >"$DMI_PRODUCT"
	ours >"$EARLY_DRACUT"
	eq "not a P16 ('$m'): ours untouched" "0|1||" "$(drop)|$(cmp -s <(ours) "$EARLY_DRACUT" && echo 1)|$(cat "$T/ih-out")|$(cat "$T/ih-err")"
	hand >"$EARLY_DRACUT"
	eq "not a P16 ('$m'): hand-written untouched, no warning" "0|1|" "$(drop)|$(cmp -s <(hand) "$EARLY_DRACUT" && echo 1)|$(cat "$T/ih-err")"
done
rm -f "$DMI_PRODUCT"
ours >"$EARLY_DRACUT"
eq "no DMI: ours untouched" "0|present" "$(drop)|$([[ -e $EARLY_DRACUT ]] && echo present)"
# shellcheck disable=SC2016 # expanded by the inner bash
eq "the default path is dracut's" /etc/dracut.conf.d/50-i2c-hid-early.conf \
	"$(env -u EARLY_DRACUT bash -c '. scripts/lib-i2c-hid.sh; echo "$EARLY_DRACUT"')"
# shellcheck disable=SC2016
eq "the default DMI file" /sys/class/dmi/id/product_name \
	"$(env -u DMI_PRODUCT bash -c '. scripts/lib-i2c-hid.sh; echo "$DMI_PRODUCT"')"

# install.sh deletes it before every initramfs refresh, in an install and in --remove.
steps_of() { # steps_of MODE: do_MODE's early_load_drop and update-initramfs calls, in order
	sed -n "/^do_$1() {/,/^}/p" scripts/install.sh |
		sed -n -e 's/^\t\(early_load_drop\)$/\1/p' -e 's/^\t\(update-initramfs\) -u -k all ||$/\1/p' | paste -sd' ' -
}
eq "install: drops it before the initramfs refresh" "early_load_drop update-initramfs" "$(steps_of install)"
eq "--remove: drops it before the initramfs refresh" "early_load_drop update-initramfs" "$(steps_of remove)"
# shellcheck disable=SC2016 # a literal $(...) in the file
eq "install.sh sources lib-i2c-hid.sh" 1 "$(grep -c '^\. "$(dirname "$0")/lib-i2c-hid\.sh"$' scripts/install.sh)"
unset -f ours hand drop steps_of

# --- check.sh: is patches/ubuntu/0002 in i2c-hid.ko? -------------------------------------------
Q=patches/ubuntu/0002-hid-i2c-hid-retry-a-failed-probe-on-the-asus-proart-p16.patch
eq "mark: 0002 logs it, once" 1 "$(grep -cF "\"probe failed (%d), $I2C_HID_RETRY_MARK\\n\"" "$Q")"
M=$T/ih-mod
mkdir -p "$M"
# A module with 0002: its format string among NULs, as in .rodata (after KERN_INFO, "\001" "6").
printf '\177ELF\0\0\0\x016probe failed (%%d), %s\n\0more\0' "$I2C_HID_RETRY_MARK" >"$M/i2c-hid.ko"
# n1x4's module (PR #2) has the P16's DMI ident but no probe retry; n1x2's has neither.
printf '\177ELF\0\0ASUS ProArt P16 H7607BA\0H7607BA\0failed to fetch HID descriptor: %%d\n\0' >"$M/n1x4.ko"
printf '\177ELF\0\0failed to fetch HID descriptor: %%d\n\0' >"$M/n1x2.ko"
eq "module: .ko with 0002" 0 "$(i2c_hid_has_retry "$M/i2c-hid.ko"; echo $?)"
eq "module: n1x4's .ko (DMI ident, no retry)" 1 "$(i2c_hid_has_retry "$M/n1x4.ko"; echo $?)"
eq "module: n1x2's .ko" 1 "$(i2c_hid_has_retry "$M/n1x2.ko"; echo $?)"
eq "module: missing" 1 "$(i2c_hid_has_retry "$M/none.ko"; echo $?)"
eq "module: no name" 1 "$(i2c_hid_has_retry ""; echo $?)"
eq "module: a directory" 1 "$(i2c_hid_has_retry "$M"; echo $?)"
printf '%s\n' "$I2C_HID_RETRY_MARK" | head -c 20 >"$M/half.ko"
eq "module: half the mark" 1 "$(i2c_hid_has_retry "$M/half.ko"; echo $?)"
# A module with the mark near its start and 256 kB after it (random, so it doesn't compress), for
# compressed files cut in half: the decompressor writes out the start, mark and all, then fails.
{ cat "$M/i2c-hid.ko"; head -c 262144 /dev/urandom; } >"$M/big.ko"
cut_half() { head -c $(($(wc -c <"$1") / 2)) "$1"; } # cut_half FILE: its first half
cut_check() { # cut_check zstd|xz FILE: whether FILE decompresses, and whether what comes out has the mark
	if "$1" -dcq -- "$2" >"$M/cut.out" 2>/dev/null; then echo decompresses; else echo fails; fi
	if LC_ALL=C grep -qaF -- "$I2C_HID_RETRY_MARK" "$M/cut.out"; then echo after the mark; fi
}
if command -v zstd >/dev/null; then
	zstd -q -c "$M/i2c-hid.ko" >"$M/i2c-hid.ko.zst"
	zstd -q -c "$M/n1x4.ko" >"$M/n1x4.ko.zst"
	eq "module: .ko.zst with 0002" 0 "$(i2c_hid_has_retry "$M/i2c-hid.ko.zst"; echo $?)"
	eq "module: .ko.zst without" 1 "$(i2c_hid_has_retry "$M/n1x4.ko.zst"; echo $?)"
	# Not compressed: zstd fails, even though the mark is in it.
	cp "$M/i2c-hid.ko" "$M/plain.ko.zst"
	eq "module: .ko.zst that is not zstd" 1 "$(i2c_hid_has_retry "$M/plain.ko.zst"; echo $?)"
	zstd -q -c "$M/big.ko" >"$M/big.ko.zst"
	cut_half "$M/big.ko.zst" >"$M/cut.ko.zst"
	eq "module: a truncated .ko.zst fails after the mark" "fails after the mark" "$(cut_check zstd "$M/cut.ko.zst" | paste -sd' ' -)"
	eq "module: truncated .ko.zst" 1 "$(i2c_hid_has_retry "$M/cut.ko.zst"; echo $?)"
else
	skip "module: .ko.zst" "no zstd"
fi
if command -v xz >/dev/null; then
	xz -c "$M/i2c-hid.ko" >"$M/i2c-hid.ko.xz"
	xz -c "$M/n1x4.ko" >"$M/n1x4.ko.xz"
	eq "module: .ko.xz with 0002" 0 "$(i2c_hid_has_retry "$M/i2c-hid.ko.xz"; echo $?)"
	eq "module: .ko.xz without" 1 "$(i2c_hid_has_retry "$M/n1x4.ko.xz"; echo $?)"
	cp "$M/i2c-hid.ko" "$M/plain.ko.xz"
	eq "module: .ko.xz that is not xz" 1 "$(i2c_hid_has_retry "$M/plain.ko.xz"; echo $?)"
	xz -q -c "$M/big.ko" >"$M/big.ko.xz"
	cut_half "$M/big.ko.xz" >"$M/cut.ko.xz"
	eq "module: a truncated .ko.xz fails after the mark" "fails after the mark" "$(cut_check xz "$M/cut.ko.xz" | paste -sd' ' -)"
	eq "module: truncated .ko.xz" 1 "$(i2c_hid_has_retry "$M/cut.ko.xz"; echo $?)"
else
	skip "module: .ko.xz" "no xz"
fi

K=7.3.0-n1x5
eq "status: OK" "OK i2c_hid retries a failed probe (patches/ubuntu/0002, $M/i2c-hid.ko)" \
	"$(i2c_hid_retry_status "$M/i2c-hid.ko" ABC123 ABC123 "$K")"
eq "status: built in" "WARN i2c_hid is built into the kernel, so whether it retries a failed probe (patches/ubuntu/0002) is unchecked" \
	"$(i2c_hid_retry_status "(builtin)" "" "" "$K")"
eq "status: no module" "FAIL no i2c_hid module (modinfo -n i2c_hid found none)" "$(i2c_hid_retry_status "" "" "" "$K")"
eq "status: module file gone" "FAIL no i2c_hid module ($M/none.ko)" "$(i2c_hid_retry_status "$M/none.ko" ABC123 "" "$K")"
eq "status: without 0002" "FAIL $M/n1x4.ko has no probe retry (patches/ubuntu/0002), so the keyboard and touchpad can stay dead after a boot" \
	"$(i2c_hid_retry_status "$M/n1x4.ko" ABC123 ABC123 "$K")"
eq "status: not loaded" "FAIL i2c_hid is not loaded" "$(i2c_hid_retry_status "$M/i2c-hid.ko" "" ABC123 "$K")"
eq "status: another module running" "FAIL running i2c_hid is not the installed $M/i2c-hid.ko: the initramfs holds another (sudo update-initramfs -u -k $K, reboot)" \
	"$(i2c_hid_retry_status "$M/i2c-hid.ko" DEF456 ABC123 "$K")"
eq "status: an unreadable srcversion is not a match" "FAIL running i2c_hid is not the installed $M/i2c-hid.ko: the initramfs holds another (sudo update-initramfs -u -k $K, reboot)" \
	"$(i2c_hid_retry_status "$M/i2c-hid.ko" DEF456 "" "$K")"
if command -v zstd >/dev/null; then
	eq "status: OK for .ko.zst (Ubuntu's)" "OK i2c_hid retries a failed probe (patches/ubuntu/0002, $M/i2c-hid.ko.zst)" \
		"$(i2c_hid_retry_status "$M/i2c-hid.ko.zst" ABC123 ABC123 "$K")"
fi
eq "check.sh: only on the P16" 1 "$(grep -c '^if is_proart_p16; then$' scripts/check.sh)"
unset -f cut_half cut_check
unset Q M K P16

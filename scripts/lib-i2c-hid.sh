# Helpers for scripts/install.sh and scripts/check.sh on the ASUS ProArt P16: i2c-hid's probe
# retry (patches/ubuntu/0002) and the early i2c-hid load an earlier install.sh set up.
# Sourced, not run; tests/t-i2c-hid.sh covers them with fake files.
# shellcheck shell=bash

DMI_PRODUCT=${DMI_PRODUCT:-/sys/class/dmi/id/product_name}

# is_proart_p16: true on the ASUS ProArt P16 H7607BA.
is_proart_p16() { [[ -r $DMI_PRODUCT ]] && grep -q H7607BA "$DMI_PRODUCT"; }

# --- the early i2c-hid load (dracut drop-in) --------------------------------------------------
# install.sh of kernels 7.3.0-n1x3 and n1x4 (never released) had dracut load i2c_mt65xx, i2c_hid
# and i2c_hid_acpi from the initramfs, for the P16's keyboard and touchpad. It didn't fix them;
# 0002's probe retry does, so install.sh deletes that drop-in again (docs/i2c-hid-probe-retry.md).
EARLY_DRACUT=${EARLY_DRACUT:-/etc/dracut.conf.d/50-i2c-hid-early.conf}
EARLY_MARK='# Generated by n1x-kernel-ubuntu (scripts/install.sh)'

# early_dracut_is_ours FILE: true if FILE is the drop-in install.sh wrote (its first line).
early_dracut_is_ours() { [[ -f $1 && $(head -1 "$1") == "$EARLY_MARK"* ]]; }

# early_load_drop: on the P16, deletes our early-load drop-in; one written by hand stays, with
# a warning. Run before install.sh refreshes every initramfs.
early_load_drop() {
	is_proart_p16 || return 0
	[[ -e $EARLY_DRACUT || -L $EARLY_DRACUT ]] || return 0
	if ! early_dracut_is_ours "$EARLY_DRACUT"; then
		warn "$EARLY_DRACUT was not written by install.sh, so it stays as it is. The keyboard and touchpad don't need i2c-hid loaded early any more (docs/i2c-hid-probe-retry.md); delete it if you don't need it for anything else."
		return 0
	fi
	rm -f "$EARLY_DRACUT"
	msg "Removed $EARLY_DRACUT: i2c-hid no longer needs to load early (patches/ubuntu/0002)"
}

# --- patches/ubuntu/0002 in the i2c-hid module ------------------------------------------------
# The format string of 0002's first log line, which only a module with the probe retry has.
I2C_HID_RETRY_MARK='retrying every %u s for up to %u s'

# i2c_hid_has_retry KO: true if the module file KO (.ko, .ko.zst or .ko.xz) has 0002.
i2c_hid_has_retry() {
	local -a st
	[[ -f $1 ]] || return 1
	case $1 in
	*.zst) zstd -dcq -- "$1" ;;
	*.xz) xz -dc -- "$1" ;;
	*) cat -- "$1" ;;
	esac 2>/dev/null | LC_ALL=C grep -aF -- "$I2C_HID_RETRY_MARK" >/dev/null
	st=("${PIPESTATUS[@]}")
	[[ ${st[0]} -eq 0 && ${st[1]} -eq 0 ]]
}

# i2c_hid_retry_status KO LOADED FILE KERNEL: check.sh's line for 0002, "OK|WARN|FAIL message".
# KO is the module file (modinfo -n i2c_hid), LOADED the running module's srcversion (empty if
# it isn't loaded), FILE that of the file (modinfo -F srcversion), KERNEL the running kernel.
i2c_hid_retry_status() {
	local ko=$1 loaded=$2 file=$3 k=$4
	if [[ $ko == "(builtin)" ]]; then
		echo "WARN i2c_hid is built into the kernel, so whether it retries a failed probe (patches/ubuntu/0002) is unchecked"
	elif [[ ! -f $ko ]]; then
		echo "FAIL no i2c_hid module (${ko:-modinfo -n i2c_hid found none})"
	elif ! i2c_hid_has_retry "$ko"; then
		echo "FAIL $ko has no probe retry (patches/ubuntu/0002), so the keyboard and touchpad can stay dead after a boot"
	elif [[ -z $loaded ]]; then
		echo "FAIL i2c_hid is not loaded"
	elif [[ $loaded != "$file" ]]; then
		echo "FAIL running i2c_hid is not the installed $ko: the initramfs holds another (sudo update-initramfs -u -k $k, reboot)"
	else
		echo "OK i2c_hid retries a failed probe (patches/ubuntu/0002, $ko)"
	fi
}

# Helpers for scripts/install.sh and scripts/check.sh: the ProArt P16's i2c-hid drivers loaded
# early from the initramfs, and the i2c-hid quirk of patches/ubuntu/0002. Sourced, not run.
# tests/t-initramfs.sh covers them with fake files and a stand-in for dpkg-query.
# shellcheck shell=bash

# With touchpad firmware V1.26.0918.1, the P16's keyboard and touchpad are dead after a warm
# reboot unless i2c-hid skips SET_POWER(SLEEP) at shutdown for every I2C HID device on it
# (patches/ubuntu/0002) and probes them
# early in the next boot, from the initramfs; from the root file system (~3 s) is too late. See
# docs/i2c-hid-warm-reboot.md. The modules: the I2C controller, the HID core, its ACPI glue.
EARLY_MODULES=(i2c_mt65xx i2c_hid i2c_hid_acpi)
# The drop-in for dracut (Ubuntu 26.04's default), and initramfs-tools' modules list, which gets
# a block between two marker lines.
EARLY_DRACUT=${EARLY_DRACUT:-/etc/dracut.conf.d/50-i2c-hid-early.conf}
EARLY_ITOOLS=${EARLY_ITOOLS:-/etc/initramfs-tools/modules}
EARLY_MARK='# Generated by n1x-kernel-ubuntu'
EARLY_BEGIN='# n1x-kernel-ubuntu: begin (scripts/install.sh writes this block, --remove deletes it)'
EARLY_END='# n1x-kernel-ubuntu: end'
DMI_PRODUCT=${DMI_PRODUCT:-/sys/class/dmi/id/product_name}

# is_proart_p16: true on the ASUS ProArt P16 H7607BA, the laptop the early load is for.
is_proart_p16() { [[ -r $DMI_PRODUCT ]] && grep -q H7607BA "$DMI_PRODUCT"; }

# initramfs_tool: prints which tool builds the initramfs, dracut or initramfs-tools (26.04's
# dracut package provides update-initramfs and conflicts with initramfs-tools). Fails if neither
# is installed.
initramfs_tool() {
	local p
	for p in dracut initramfs-tools; do
		if [[ $(dpkg-query -W -f '${db:Status-Abbrev}' "$p" 2>/dev/null) == ii* ]]; then
			printf '%s\n' "$p"
			return 0
		fi
	done
	return 1
}

# early_dracut_text: our dracut drop-in.
early_dracut_text() {
	cat <<-EOF
		$EARLY_MARK (scripts/install.sh): load the ProArt P16's i2c-hid drivers early,
		# from the initramfs. With touchpad firmware V1.26.0918.1 the keyboard and touchpad die on
		# a warm reboot if they are probed late (docs/i2c-hid-warm-reboot.md).
		# scripts/install.sh --remove deletes this. Remove by hand: sudo rm $EARLY_DRACUT;
		# sudo update-initramfs -u -k all
		force_drivers+=" ${EARLY_MODULES[*]} "
	EOF
}

# early_settings FILE: FILE's lines without comments and blank lines.
early_settings() { grep -v -e '^[[:space:]]*#' -e '^[[:space:]]*$' "$1" 2>/dev/null || true; }

# early_dracut_is_ours FILE: true if FILE is a drop-in early_dracut_text wrote.
early_dracut_is_ours() { [[ -f $1 && $(head -1 "$1") == "$EARLY_MARK "* ]]; }

# early_dracut_adoptable FILE: true if install.sh may write FILE: it is missing, ours, or one
# written by hand that sets exactly what ours does (the one rtx24 was tested with), which ours
# then replaces.
early_dracut_adoptable() {
	[[ ! -e $1 ]] || early_dracut_is_ours "$1" ||
		[[ -f $1 && $(early_settings "$1") == "$(early_settings <(early_dracut_text))" ]]
}

# early_itools_without FILE: FILE (initramfs-tools' modules list) without our block.
early_itools_without() {
	[[ -f $1 ]] || return 0
	awk -v b="$EARLY_BEGIN" -v e="$EARLY_END" '$0 == b {skip = 1; next} skip && $0 == e {skip = 0; next} !skip' "$1"
}

# early_itools_with FILE: FILE without our block, then our block (one module per line).
early_itools_with() {
	early_itools_without "$1"
	printf '%s\n' "$EARLY_BEGIN" "${EARLY_MODULES[@]}" "$EARLY_END"
}

# early_load_missing LISTING PRELOAD: what an initramfs lacks for the early load, one item per
# line (nothing if it has it all). LISTING is its file list (lsinitrd, lsinitramfs), PRELOAD
# the modules it loads first, one per line: dracut's rd.driver.pre= lines
# (etc/cmdline.d/20-force_drivers.conf) or initramfs-tools' conf/modules. Modules in an
# updates/ directory don't count: they are not the kernel's own.
early_load_missing() {
	local m f list pre
	list=$(cat "$1") pre=$(sed -e 's/^rd\.driver\.pre=//' -e 's/[, ]/\n/g' "$2")
	for m in "${EARLY_MODULES[@]}"; do
		f=${m//_/-}.ko
		grep -qE "(^|[ /])kernel/drivers/[^ ]*/${f//./\\.}(\.[a-z]+)?\$" <<<"$list" || echo "no $f"
		grep -qxF "$m" <<<"$pre" || echo "$m not loaded first"
	done
	return 0
}

# patches/ubuntu/0002's DMI table entry for the P16, whose .ident string is in i2c-hid.ko. A
# module without it puts every I2C HID device to sleep at shutdown.
I2C_HID_QUIRK_IDENT='ASUS ProArt P16 H7607BA'

# i2c_hid_has_quirk KO: true if the module file KO (.ko, .ko.zst or .ko.xz) has 0002's DMI entry.
i2c_hid_has_quirk() {
	local f=$1 tmp="" bad=0
	[[ -f $f ]] || return 1
	case $f in
	*.zst | *.xz)
		tmp=$(mktemp) || return 1
		if [[ $f == *.zst ]]; then zstd -dcq "$f"; else xz -dc "$f"; fi >"$tmp" 2>/dev/null ||
			{ rm -f "$tmp"; return 1; }
		f=$tmp
		;;
	esac
	LC_ALL=C grep -qaF "$I2C_HID_QUIRK_IDENT" "$f" || bad=1
	[[ -z $tmp ]] || rm -f "$tmp"
	return "$bad"
}
